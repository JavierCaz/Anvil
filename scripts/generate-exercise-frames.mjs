/**
 * Generates the exercise pose frames and `src/constants/exercise-frames.ts`.
 *
 * 1. Converts each catalog exercise's first frame from @bryllim/workout-guide
 *    (512 px palette PNG) to lossless WebP in `assets/exercises/<slug>.webp`.
 *    Lossless keeps the line art pixel-identical while roughly a third
 *    smaller than the PNGs. Existing WebPs are kept unless `--force` is passed.
 * 2. Emits one literal `require()` per exercise — React Native/Metro does not
 *    support dynamic require paths.
 *
 * The WebPs are committed, so builds (including F-Droid's) don't need
 * ImageMagick. Run after updating the package (requires ImageMagick 7):
 *   node scripts/generate-exercise-frames.mjs [--force]
 */
import { execFile } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { availableParallelism } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { promisify } from 'node:util';

const run = promisify(execFile);
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const packageDir = join(root, 'node_modules/@bryllim/workout-guide');
const outDir = join(root, 'assets/exercises');
const force = process.argv.includes('--force');

const manifest = JSON.parse(readFileSync(join(packageDir, 'manifest.json'), 'utf8'));
mkdirSync(outDir, { recursive: true });

/** PNG → lossless WebP, metadata stripped so output is reproducible. */
async function convert(slug) {
  const target = join(outDir, `${slug}.webp`);
  if (!force && existsSync(target)) return false;
  await run('magick', [
    join(packageDir, 'assets', slug, 'frame-1.png'),
    '-strip',
    '-define', 'webp:lossless=true',
    '-define', 'webp:method=6',
    '-define', 'webp:exact=true',
    target,
  ]);
  return true;
}

const queue = manifest.map((exercise) => exercise.slug);
let converted = 0;
await Promise.all(
  Array.from({ length: availableParallelism() }, async () => {
    for (let slug = queue.shift(); slug; slug = queue.shift()) {
      if (await convert(slug)) converted += 1;
    }
  })
);

const lines = [
  '/**',
  ' * Generated by scripts/generate-exercise-frames.mjs — do not edit by hand.',
  ' *',
  ' * Maps each catalog exercise slug to its first pose frame (lossless WebP in',
  ' * assets/exercises/). Literal require() paths are required by React Native/Metro.',
  ' * Artwork: Everkinetic, expanded by Bryl Lim (CC BY-SA 4.0).',
  ' */',
  "import type { ImageSourcePropType } from 'react-native';",
  '',
];
const entries = [];

for (const exercise of manifest) {
  const key = `frame_${exercise.slug.replace(/[^a-zA-Z0-9_]/g, '_')}`;
  lines.push(
    `const ${key} = require('../../assets/exercises/${exercise.slug}.webp') as ImageSourcePropType;`
  );
  entries.push(`  '${exercise.slug}': ${key},`);
}

lines.push('');
lines.push('export const EXERCISE_FRAMES: Record<string, ImageSourcePropType> = {');
lines.push(entries.join('\n'));
lines.push('};');
lines.push('');

const outPath = join(root, 'src/constants/exercise-frames.ts');
writeFileSync(outPath, lines.join('\n'));
console.log(`Converted ${converted} frames; wrote ${manifest.length} entries to ${outPath}`);
