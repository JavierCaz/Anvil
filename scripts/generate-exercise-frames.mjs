/**
 * Generates `src/constants/exercise-frames.ts`.
 *
 * React Native/Metro requires literal `require()` paths — dynamic path
 * assembly is not supported. This script reads the @bryllim/workout-guide
 * manifest and emits one literal `require()` per catalog exercise (frame 1).
 *
 * Run after updating the package:
 *   node scripts/generate-exercise-frames.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const manifest = JSON.parse(
  readFileSync(join(root, 'node_modules/@bryllim/workout-guide/manifest.json'), 'utf8')
);

const lines = [
  '/**',
  ' * Generated by scripts/generate-exercise-frames.mjs — do not edit by hand.',
  ' *',
  ' * Maps each catalog exercise slug to its first pose frame (frame-1.png).',
  ' * Literal require() paths are required by React Native/Metro.',
  ' * Artwork: Everkinetic, expanded by Bryl Lim (CC BY-SA 4.0).',
  ' */',
  "import type { ImageSourcePropType } from 'react-native';",
  '',
];
const entries = [];

for (const exercise of manifest) {
  const key = `frame_${exercise.slug.replace(/[^a-zA-Z0-9_]/g, '_')}`;
  const path = `@bryllim/workout-guide/assets/${exercise.slug}/frame-1.png`;
  lines.push(
    `const ${key} = require('${path}') as ImageSourcePropType;`
  );
  entries.push(`  '${exercise.slug}': ${key},`);
}

lines.push('');
lines.push('export const EXERCISE_FRAMES: Record<string, ImageSourcePropType> = {');
lines.push(entries.join('\n'));
lines.push('};');
lines.push('');

const outPath = join(root, 'src/constants/exercise-frames.ts');
writeFileSync(outPath, lines.join('\n'));
console.log(`Wrote ${manifest.length} frame entries to ${outPath}`);
